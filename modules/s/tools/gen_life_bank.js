/* --- 5.1 和差问题：已知两数的和与差，求大数 --- */
function sumDiff() {
  const small = R(3, 40), d = R(2, 20);
  const big = small + d;
  const right = big;
  const wrongs = uniq([small, big + d, Math.max(0, big - d), big + R(1, 6)]).map(String);
  return choice('两个数相加是 ' + (big + small) + '，相减是 ' + d + '，较大的那个数是多少？',
    String(right), wrongs, {
      kp: '和差问题', tag: '和差问题',
      teach: '大数 =（和＋差）÷ 2 =（' + (big + small) + '＋' + d + '）÷ 2 = ' + big + '。',
      say: '较大的那个数是多少？'
    });
}
/* --- 5.2 和倍问题 --- */
function sumTimes() {
  const k = R(2, 6), small = R(3, 15);
  const big = small * k;
  const right = small;
  const wrongs = uniq([big, big + small, small + R(1, 5), Math.max(0, small - R(1, 2))]).map(String);
  return choice('甲乙两数的和是 ' + (big + small) + '，甲是乙的 ' + k + ' 倍，乙是多少？',
    String(right), wrongs, {
      kp: '和倍问题', tag: '和倍问题',
      teach: '把乙看作 1 份，甲是 ' + k + ' 份，共 ' + (k + 1) + ' 份。' + (big + small) + '÷' + (k + 1) + ' = ' + small + '，乙是 ' + small + '。',
      say: '乙是多少？'
    });
}
/* --- 5.3 差倍问题 --- */
function diffTimes() {
  const k = R(2, 6), small = R(2, 15);
  const big = small * k;
  const d = big - small;
  const right = small;
  const wrongs = uniq([big, d, big + small, Math.max(1, small - R(1, 2))]).map(String);
  return choice('甲比乙多 ' + d + '，且甲是乙的 ' + k + ' 倍，乙是多少？',
    String(right), wrongs, {
      kp: '差倍问题', tag: '差倍问题',
      teach: '把乙看作 1 份，甲比乙多 ' + (k - 1) + ' 份，正好是 ' + d + '。' + d + '÷' + (k - 1) + ' = ' + small + '，乙是 ' + small + '。',
      say: '乙是多少？'
    });
}
/* --- 5.4 鸡兔同笼（假设法） --- */
function rabbit() {
  const rab = R(2, 12), chi = R(2, 15);
  const H = rab + chi, F = rab * 4 + chi * 2;
  const right = rab;
  const wrongs = uniq([chi, H, Math.max(0, rab - R(1, 3)), rab + R(1, 4)]).map(String);
  return choice('鸡兔同笼，一共有 ' + H + ' 个头，' + F + ' 只脚。兔子有几只？',
    String(right), wrongs, {
      kp: '鸡兔同笼', tag: '鸡兔同笼',
      teach: '假设全是鸡：' + H + '×2 = ' + (H * 2) + ' 只脚，比实际少 ' + (F - H * 2) +
        ' 只。每把 1 只鸡换成兔多 2 只脚，' + (F - H * 2) + '÷2 = ' + rab + '，兔子有 ' + rab + ' 只。',
      say: '兔子有几只？'
    });
}
/* --- 5.5 植树问题 --- */
function plant() {
  const gap = R(3, 12), n = R(4, 15);
  const len = gap * n;
  const right = n + 1;
  const wrongs = uniq([n, n - 1, n + 2, n + 3]).map(String);
  return choice('一条小路长 ' + len + ' 米，从头到尾每隔 ' + gap + ' 米栽一棵树（两端都栽），一共要栽多少棵？',
    String(right), wrongs, {
      kp: '植树问题', tag: '植树问题',
      teach: '段数 = ' + len + '÷' + gap + ' = ' + n + '，两端都栽：棵数 = 段数＋1 = ' + (n + 1) + '。',
      say: '一共要栽多少棵？'
    });
}
/* --- 5.6 归一问题 --- */
function unitRate() {
  const n1 = R(2, 9), price = R(2, 9), n2 = R(2, 9);
  const right = price * n2;
  const wrongs = uniq([right + R(1, 6), Math.max(1, right - R(1, 6)), n1 * price + n2, right + R(7, 12)]).map(String);
  return choice(n1 + ' 支铅笔 ' + (n1 * price) + ' 元，买 ' + n2 + ' 支要多少元？',
    String(right), wrongs, {
      kp: '归一问题', tag: '归一问题',
      teach: '先求 1 支：' + (n1 * price) + '÷' + n1 + ' = ' + price + ' 元，再求 ' + n2 + ' 支：' + price + '×' + n2 + ' = ' + right + ' 元。',
      say: '买这些要多少元？'
    });
}
/* --- 5.7 年龄问题（年龄差不变） --- */
function ageQ() {
  const d = R(10, 30), child = R(4, 12);
  const parent = child + d;
  const right = d;
  const wrongs = uniq([d + R(1, 5), Math.max(1, d - R(1, 5)), parent, child]).map(String);
  return choice('今年爸爸 ' + parent + ' 岁，儿子 ' + child + ' 岁。再过 10 年，爸爸比儿子大多少岁？',
    String(right), wrongs, {
      kp: '年龄问题', tag: '年龄问题',
      teach: '年龄差永远不变：' + parent + '－' + child + ' = ' + d + ' 岁。10 年后两人都长 10 岁，差还是 ' + d + ' 岁。',
      say: '爸爸比儿子大多少岁？'
    });
}


