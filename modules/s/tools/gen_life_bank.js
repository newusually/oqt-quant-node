/* 兼容两种写法：
 *   嵌套式  [题干, 答案, [干扰1, 干扰2, 干扰3], 讲解?]
 *   扁平式  [题干, 答案, 干扰1, 干扰2, 干扰3]          */
function fromList(list, kp) {
  const out = [];
  list.forEach(function (it) {
    let wrongs, teach;
    if (Array.isArray(it[2])) { wrongs = it[2]; teach = it[3]; }
    else { wrongs = [it[2], it[3], it[4]]; teach = it[5]; }
    const q = choice(it[0], it[1], wrongs, {
      kp: kp, tag: kp,
      teach: teach || (it[0] + ' 答案是“' + it[1] + '”。'),
      say: it[0]
    });
    if (q) out.push(q);
  });
  return out;
}

